"""### Prepare experiment"""

# Create six-month windows using the authors' approach

window_size_months = 6

min_month = combined_df["Travel Month"].min()
max_month = combined_df["Travel Month"].max()

windows = []

for start_month in range(min_month, max_month - window_size_months + 2):
    end_month = start_month + window_size_months

    window_df = combined_df[
        (combined_df["Travel Month"] >= start_month) &
        (combined_df["Travel Month"] < end_month)
    ].copy()

    windows.append(window_df)

    print(
        f"Window {len(windows)}: "
        f"Months {start_month}–{end_month - 1}, "
        f"Records: {len(window_df):,}"
    )

print("\nTotal windows:", len(windows))

import numpy as np
import tensorflow as tf
from sklearn.metrics import mean_absolute_error, mean_squared_error
from Scripts.Long_Sequence_Models.Bidirectional_LSTM_model import Bidirectional_LSTM_model

# Reproducibility
tf.keras.utils.set_random_seed(42)

# Select the first six-month window
window_df = windows[0].copy()

# Separate features and target
X = window_df.drop(columns=["Price ($)"]).to_numpy(dtype=np.float32)
y = window_df["Price ($)"].to_numpy(dtype=np.float32)

# Chronological 80/10/10 split
train_size = int(0.8 * len(X))
val_size = int(0.1 * len(X))

X_train = X[:train_size]
y_train = y[:train_size]

X_val = X[train_size:train_size + val_size]
y_val = y[train_size:train_size + val_size]

X_test = X[train_size + val_size:]
y_test = y[train_size + val_size:]

# Reshape for LSTM: (samples, timesteps, features)
X_train = np.expand_dims(X_train, axis=1)
X_val = np.expand_dims(X_val, axis=1)
X_test = np.expand_dims(X_test, axis=1)

print("Training:", X_train.shape)
print("Validation:", X_val.shape)
print("Testing:", X_test.shape)

# Build original model
tf.keras.backend.clear_session()
model = Bidirectional_LSTM_model(
    input_shape=(1, X_train.shape[2])
)

model.compile(
    optimizer=tf.keras.optimizers.Adam(learning_rate=0.001),
    loss="mean_squared_error"
)

# Stop when validation loss stops improving
early_stopping = tf.keras.callbacks.EarlyStopping(
    monitor="val_loss",
    patience=25,
    restore_best_weights=True
)

# Train model
history = model.fit(
    X_train,
    y_train,
    validation_data=(X_val, y_val),
    epochs=100,
    batch_size=32,
    callbacks=[early_stopping],
    verbose=2
)

# Evaluate on unseen test data
predictions = model.predict(X_test, verbose=0).flatten()

mae = mean_absolute_error(y_test, predictions)
mse = mean_squared_error(y_test, predictions)

print("\nFINAL RESULTS — WINDOW 1")
print(f"MAE: ${mae:.2f}")
print(f"MSE: {mse:.2f}")
print(f"Epochs completed: {len(history.history['loss'])}")